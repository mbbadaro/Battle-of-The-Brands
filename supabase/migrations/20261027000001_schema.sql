-- Battle of the Brands sales tracker: core schema, row level security and realtime.
--
-- Inventory is a ledger, never a mutable counter:
--   remaining = initial_inventory + sum(adjustments.delta) - sum(bars of completed transactions)
-- All writes go through SECURITY DEFINER functions (next migration) that take a row
-- lock on event_settings, so sales, voids and adjustments are serialized and two
-- sellers can never sell the same remaining stock.

create schema if not exists private;
revoke all on schema private from public;

create type public.app_role as enum ('pending', 'seller', 'admin');
create type public.customer_category as enum ('first_year_mba', 'second_year_mba', 'faculty', 'other_unknown');
create type public.txn_status as enum ('completed', 'voided');
create type public.adjustment_kind as enum ('restock', 'correction');

-- Team members. A row is created automatically for every new auth user.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  display_name text not null check (char_length(display_name) between 1 and 60),
  role public.app_role not null default 'pending',
  created_at timestamptz not null default now()
);

-- Singleton event configuration.
create table public.event_settings (
  id smallint primary key default 1 check (id = 1),
  event_name text not null default 'Cornell MBA Battle of the Brands',
  initial_inventory integer not null default 200 check (initial_inventory between 0 and 100000),
  timezone text not null default 'America/New_York',
  -- Set by the first sale. Once set, initial inventory is locked and changes go through adjustments.
  sales_started_at timestamptz,
  -- A second sale for the same NetID inside this window needs explicit confirmation.
  duplicate_window_seconds integer not null default 120 check (duplicate_window_seconds between 0 and 3600),
  -- Sellers may undo their own sale for this many minutes; admins can void any sale at any time.
  seller_undo_minutes integer not null default 5 check (seller_undo_minutes between 0 and 120),
  updated_at timestamptz not null default now()
);

create table public.products (
  id text primary key check (id ~ '^[a-z_]{2,20}$'),
  name text not null check (char_length(name) between 1 and 60),
  tagline text,
  bars_per_unit integer not null check (bars_per_unit > 0),
  tickets_per_unit integer not null check (tickets_per_unit > 0),
  active boolean not null default true,
  sort_order integer not null default 0
);

create table public.transactions (
  id bigint generated always as identity primary key,
  -- Generated by the client once per sale attempt; makes retries and double taps idempotent.
  client_request_id uuid not null unique,
  created_at timestamptz not null default now(),
  seller_id uuid not null references public.profiles (id),
  netid text not null check (netid ~ '^[a-z]{1,4}[0-9]{1,6}$'),
  customer_name text check (customer_name is null or char_length(customer_name) between 1 and 80),
  customer_category public.customer_category,
  total_bars integer not null check (total_bars > 0),
  total_tickets integer not null check (total_tickets > 0),
  status public.txn_status not null default 'completed',
  voided_at timestamptz,
  voided_by uuid references public.profiles (id),
  void_reason text,
  constraint void_fields_consistent check (
    (status = 'voided') = (voided_at is not null and voided_by is not null and void_reason is not null)
  )
);
create index transactions_created_at_idx on public.transactions (created_at desc);
create index transactions_netid_idx on public.transactions (netid, created_at desc);
create index transactions_seller_idx on public.transactions (seller_id, created_at desc);

-- One row per product in a transaction. Unit bars/tickets are snapshotted at sale time.
create table public.transaction_items (
  transaction_id bigint not null references public.transactions (id) on delete cascade,
  product_id text not null references public.products (id),
  quantity integer not null check (quantity between 1 and 100),
  bars_per_unit integer not null check (bars_per_unit > 0),
  tickets_per_unit integer not null check (tickets_per_unit > 0),
  bars integer generated always as (quantity * bars_per_unit) stored,
  tickets integer generated always as (quantity * tickets_per_unit) stored,
  primary key (transaction_id, product_id)
);

create table public.inventory_adjustments (
  id bigint generated always as identity primary key,
  created_at timestamptz not null default now(),
  created_by uuid not null references public.profiles (id),
  kind public.adjustment_kind not null,
  delta integer not null check (delta <> 0 and delta between -100000 and 100000),
  reason text not null check (char_length(reason) between 3 and 300)
);

-- Append-only record of every administrative action and every void.
create table public.audit_log (
  id bigint generated always as identity primary key,
  created_at timestamptz not null default now(),
  actor_id uuid references public.profiles (id),
  action text not null,
  entity text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb
);
create index audit_log_created_at_idx on public.audit_log (created_at desc);

-- Bumped by every write. Clients subscribe to it through Supabase Realtime and refetch.
-- Using a signal row (instead of streaming transactions) keeps NetIDs out of the realtime feed.
create table public.live_ticker (
  id smallint primary key default 1 check (id = 1),
  version bigint not null default 0,
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Role helpers (SECURITY DEFINER so policies can call them without recursion)
-- ---------------------------------------------------------------------------
create or replace function private.my_role() returns public.app_role
language sql stable security definer set search_path = '' as $$
  select p.role from public.profiles p where p.id = auth.uid()
$$;

create or replace function private.is_team_member() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(private.my_role() in ('seller', 'admin'), false)
$$;

create or replace function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(private.my_role() = 'admin', false)
$$;

grant usage on schema private to authenticated;
grant execute on function private.my_role(), private.is_team_member(), private.is_admin() to authenticated;

-- ---------------------------------------------------------------------------
-- Row level security. Tables are read-only to clients; every write is an RPC.
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.event_settings enable row level security;
alter table public.products enable row level security;
alter table public.transactions enable row level security;
alter table public.transaction_items enable row level security;
alter table public.inventory_adjustments enable row level security;
alter table public.audit_log enable row level security;
alter table public.live_ticker enable row level security;

revoke all on all tables in schema public from anon;
revoke insert, update, delete, truncate on all tables in schema public from authenticated;
grant select on all tables in schema public to authenticated;

create policy "own profile or admin" on public.profiles
  for select to authenticated using (id = auth.uid() or private.is_admin());

create policy "team reads settings" on public.event_settings
  for select to authenticated using (private.is_team_member());

create policy "team reads products" on public.products
  for select to authenticated using (private.is_team_member());

-- Sellers only see the sales they entered (needed for undo); admins see everything.
create policy "admin or own sales" on public.transactions
  for select to authenticated using (private.is_admin() or (seller_id = auth.uid() and private.is_team_member()));

create policy "admin or own sale items" on public.transaction_items
  for select to authenticated using (
    private.is_admin() or exists (
      select 1 from public.transactions t
      where t.id = transaction_id and t.seller_id = auth.uid() and private.is_team_member()
    )
  );

create policy "admin reads adjustments" on public.inventory_adjustments
  for select to authenticated using (private.is_admin());

create policy "admin reads audit log" on public.audit_log
  for select to authenticated using (private.is_admin());

create policy "team reads ticker" on public.live_ticker
  for select to authenticated using (private.is_team_member());

-- Realtime: only the ticker is published.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.live_ticker;
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- New auth users get a profile. The very first user becomes admin; everyone
-- after that waits as 'pending' until an admin approves them.
-- ---------------------------------------------------------------------------
create or replace function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_name text;
  v_role public.app_role;
begin
  perform pg_advisory_xact_lock(hashtext('bob_first_admin'));
  v_name := left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), split_part(new.email, '@', 1), 'Team member'), 60);
  if exists (select 1 from public.profiles where role = 'admin') then
    v_role := 'pending';
  else
    v_role := 'admin';
  end if;
  insert into public.profiles (id, email, display_name, role) values (new.id, new.email, v_name, v_role);
  insert into public.audit_log (actor_id, action, entity, entity_id, details)
  values (new.id, 'user_signed_up', 'profile', new.id::text, jsonb_build_object('role', v_role, 'email', new.email));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();
